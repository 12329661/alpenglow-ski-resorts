// Decodes world-atlas land-110m TopoJSON into a single equirectangular SVG path
// string and writes it to lib/world-map-path.ts. No runtime deps.
//   path space: x = lon + 180  (0..360),  y = 90 - lat  (0..180)
import { readFileSync, writeFileSync } from "node:fs";

const topo = JSON.parse(readFileSync(process.argv[2], "utf8"));
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;

// Decode every arc from delta-quantised ints to [lon, lat] pairs.
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});

function arcCoords(index) {
  if (index >= 0) return arcs[index];
  return arcs[~index].slice().reverse();
}

function ring(arcIndexes) {
  const pts = [];
  for (const idx of arcIndexes) {
    const seg = arcCoords(idx);
    // arcs share endpoints — drop the first point of every segment after the first
    pts.push(...(pts.length ? seg.slice(1) : seg));
  }
  return pts;
}

const round = (n) => Math.round(n * 100) / 100;

function ringToPath(pts) {
  let d = "";
  let prevLon = null;
  for (let i = 0; i < pts.length; i++) {
    const [lon, lat] = pts[i];
    const px = round(lon + 180);
    const py = round(90 - lat);
    // Break the stroke across antimeridian jumps (Russia, Fiji, …) so the
    // projection doesn't draw a horizontal seam right across the map.
    const cmd = i === 0 || (prevLon !== null && Math.abs(lon - prevLon) > 180)
      ? "M"
      : "L";
    d += `${cmd}${px} ${py}`;
    prevLon = lon;
  }
  return d + "Z";
}

let d = "";
for (const geom of topo.objects.land.geometries) {
  const polygons = geom.type === "Polygon" ? [geom.arcs] : geom.arcs;
  for (const poly of polygons) {
    for (const r of poly) d += ringToPath(ring(r));
  }
}

const out = `// Auto-generated by scripts/build-world-path.mjs from world-atlas land-110m.
// Equirectangular land outline. Path space: x = lon + 180 (0..360), y = 90 - lat (0..180).
export const WORLD_MAP_PATH =
  ${JSON.stringify(d)};
`;

writeFileSync(new URL("../lib/world-map-path.ts", import.meta.url), out);
console.error(`wrote lib/world-map-path.ts (${d.length} chars)`);
